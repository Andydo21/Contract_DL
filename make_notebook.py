    "            if len(poly) == 4 and isinstance(poly[0], (int, float)):\n",
    "                x0, y0, x1, y1 = poly\n",
    "            else:\n",
    "                xs = [p[0] for p in poly]\n",
    "                ys = [p[1] for p in poly]\n",
    "                x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)\n",
    "            words.append({\n",
    "                'text': text,\n",
    "                'conf': float(getattr(ln, 'confidence', 0) or 0),\n",
    "                'x0': x0 * sx,\n",
    "                'y0': y0 * sy,\n",
    "                'x1': x1 * sx,\n",
    "                'y1': y1 * sy\n",
    "            })\n",
    "        return words\n",
